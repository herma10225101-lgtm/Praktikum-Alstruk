# 1. Data awal
nilai = 82
kehadiran = 90

print("=== Kondisi Awal (Nilai = 82, Kehadiran = 90%) ===")
# 2. Operator >= untuk memeriksa syarat
syarat_nilai = nilai >= 75
syarat_kehadiran = kehadiran >= 80

print("Syarat Nilai (>= 75)     :", syarat_nilai)
print("Syarat Kehadiran (>= 80%):", syarat_kehadiran)

# 3. Operator AND untuk syarat kelulusan
lulus_and = syarat_nilai and syarat_kehadiran
print("Status Lulus (AND)       :", lulus_and)

# 4. Mengubah nilai menjadi 70
nilai = 70
print("\n=== Setelah Nilai Diubah menjadi 70 ===")
syarat_nilai_baru = nilai >= 75
lulus_and_baru = syarat_nilai_baru and syarat_kehadiran
lulus_or = syarat_nilai_baru or syarat_kehadiran

print("Syarat Nilai Baru (70 >= 75):", syarat_nilai_baru)
print("Status Lulus dengan AND     :", lulus_and_baru)

# 5. Menggunakan operator OR
print("Status Lulus dengan OR      :", lulus_or)