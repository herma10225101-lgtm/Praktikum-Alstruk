def rekap_nilai(nama: str, nilai_tugas: float, nilai_ujian: float):
    # Hitung rata-rata
    rata_rata = (nilai_tugas + nilai_ujian) / 2

    # Periksa status kelulusan (minimal 75)
    status_lulus = rata_rata >= 75

    # Tampilkan rekapitulasi
    print("=" * 40)
    print(f"Nama Mahasiswa : {nama}")
    print(f"Nilai Tugas    : {nilai_tugas}")
    print(f"Nilai Ujian    : {nilai_ujian}")
    print(f"Rata-rata      : {rata_rata:.2f}")
    print(f"Status Lulus   : {status_lulus}")
    print("=" * 40 + "\n")

# Uji Coba 1: Herma (Lulus)
rekap_nilai("Herma", 85, 80)

# Uji Coba 2: Herma (Tidak Lulus)
rekap_nilai("Herma", 60, 70)